/* ───────────── Product imagery ───────────── */

/**
 * Catalogue product shot with a graceful fallback (a soft colour swatch) when the
 * image is missing — placeholders are generated by `npm run assets`.
 */
export function ProductImage({
  sku,
  variant = "primary",
  className,
  alt,
}: {
  sku: Sku;
  variant?: "primary" | "alt";
  className?: string;
  alt?: string;
}) {
  const src = variant === "alt" && sku.altImage ? sku.altImage : sku.image;
  const [failedSrc, setFailedSrc] = useState<string | null>(null);
  const label = alt ?? `${sku.name} product photo`;

  if (failedSrc === src) {
    return (
      <div role="img" aria-label={label} className={cx("relative overflow-hidden bg-surface-2", className)}>
        <span
          aria-hidden
          className="absolute inset-x-[22%] bottom-[10%] top-[16%] rounded-t-[45%] rounded-b-[14%] opacity-90"
          style={{ backgroundColor: sku.colorHex }}
        />
      </div>
    );
  }
  return (
    // eslint-disable-next-line @next/next/no-img-element -- static catalogue asset; sizes vary, no optimisation needed
    <img
      src={src}
      alt={label}
      draggable={false}
      decoding="async"
      className={cx("bg-white object-contain", className)}
      onError={() => setFailedSrc(src)}
      ref={(el) => {
        // An image that failed before hydration never fires onError for React.
        if (el && el.complete && el.naturalWidth === 0 && failedSrc !== src) setFailedSrc(src);
      }}
    />
  );
}

