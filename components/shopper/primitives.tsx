/* ───────────── Buttons that aren't <button> (links, file pickers) ───────────── */

export type ButtonVariant = "primary" | "secondary" | "ghost";
export type ButtonSize = "sm" | "md" | "lg";

/** Same look as components/ui Button, for <Link> and <label> elements. */
export function buttonClass(variant: ButtonVariant = "primary", size: ButtonSize = "md"): string {
  return cx(
    "inline-flex items-center justify-center gap-2 rounded-xl font-medium transition-colors",
    "focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-accent",
    size === "sm" && "h-9 px-3 text-sm",
    size === "md" && "h-11 px-4 text-[15px]",
    size === "lg" && "h-13 px-5 text-base",
    variant === "primary" && "bg-accent text-accent-ink hover:opacity-90",
    variant === "secondary" && "border border-line bg-surface text-ink hover:bg-surface-2",
    variant === "ghost" && "text-muted hover:bg-surface-2 hover:text-ink",
  );
}

export function LinkButton({
  href,
  variant = "primary",
  size = "md",
  className,
  children,
}: {
  href: string;
  variant?: ButtonVariant;
  size?: ButtonSize;
  className?: string;
  children: ReactNode;
}) {
  return (
    <Link href={href} className={cx(buttonClass(variant, size), className)}>
      {children}
    </Link>
  );
}

/** A file picker that looks like a button. The native input stays focusable for keyboard + screen readers. */
export function PhotoFileButton({
  onFile,
  disabled,
  useCamera = false,
  variant = "secondary",
  size = "lg",
  className,
  describedBy,
  children,
}: {
  onFile: (file: File) => void;
  disabled?: boolean;
  /** Adds capture="user": opens the phone's camera app directly. */
  useCamera?: boolean;
  variant?: ButtonVariant;
  size?: ButtonSize;
  className?: string;
  describedBy?: string;
  children: ReactNode;
}) {
  const id = useId();
  return (
    <label
      htmlFor={id}
      aria-disabled={disabled || undefined}
      className={cx(
        buttonClass(variant, size),
        "has-[input:focus-visible]:outline-2 has-[input:focus-visible]:outline-offset-2 has-[input:focus-visible]:outline-accent",
        disabled ? "pointer-events-none cursor-not-allowed opacity-50" : "cursor-pointer",
        className,
      )}
    >
      <input
        id={id}
        type="file"
        accept="image/*"
        capture={useCamera ? "user" : undefined}
        disabled={disabled}
        aria-describedby={describedBy}
        className="sr-only"
        onChange={(e) => {
          const file = e.currentTarget.files?.[0];
          e.currentTarget.value = "";
          if (file) onFile(file);
        }}
      />
      {children}
    </label>
  );
}

